for (const file of fs.readdirSync(dir).filter((name) => name.endsWith(".json"))) {
  const full = path.join(dir, file);
  const catalog = JSON.parse(fs.readFileSync(full, "utf8"));
  catalog.strings = { ...(catalog.strings ?? {}) };
  for (const [key, value] of Object.entries(english)) {
    if (!(key in catalog.strings)) catalog.strings[key] = value;
  }
  if (file === "zh-Hans.json") Object.assign(catalog.strings, zhHans);
  fs.writeFileSync(full, JSON.stringify(catalog, null, 2) + "\n", "utf8");
}

console.log(`Added ${Object.keys(english).length} dashboard localization keys.`);
